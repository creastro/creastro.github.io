/* Preset selector for the Doppler simulation: loads the spin of a real directly imaged planet or brown dwarf
   (inclination and equatorial speed) and shows where each number comes from. Data: presets.js, generated by
   presets/build_presets.py. Nothing is defaulted: a missing element or missing data is an error. */
(() => {
  'use strict';
  const need = (id) => { const el = document.getElementById(id); if (!el) throw new Error('presets-ui: #' + id + ' not found'); return el; };
  if (!window.SIM_PRESETS) throw new Error('presets-ui: presets.js did not define SIM_PRESETS');
  const items = window.SIM_PRESETS.items;
  const select = need('preset'), card = need('preset-card'), inc = need('inc'), veq = need('veq'), form = need('controls');
  const byId = new Map(items.map((p) => [p.id, p]));

  const el = (tag, cls, text) => { const e = document.createElement(tag); if (cls) e.className = cls; if (text !== undefined) e.textContent = text; return e; };
  const link = (text, url) => { const a = el('a', '', text); a.href = url; a.target = '_blank'; a.rel = 'noopener noreferrer'; return a; };

  // options, in two groups
  select.appendChild(new Option('Custom: set the sliders yourself', ''));
  [['Directly imaged planets and companions', (p) => p.kind !== 'brown dwarf'], ['Brown dwarf', (p) => p.kind === 'brown dwarf']].forEach(([label, test]) => {
    const group = document.createElement('optgroup');
    group.label = label;
    items.filter(test).forEach((p) => group.appendChild(new Option(p.label, p.id)));
    select.appendChild(group);
  });

  function fmt1(v) { return (Math.round(v * 10) / 10).toString(); }

  function render(p) {
    card.textContent = '';
    card.classList.remove('modified');
    card.appendChild(el('h3', '', p.label));
    card.appendChild(el('p', 'kind', p.kind));
    card.appendChild(el('p', 'modified', 'You changed a slider. The values below describe the preset, not the current settings.'));
    const sets = el('p', 'sets');
    sets.append('Sets the inclination to ');
    sets.appendChild(el('b', '', fmt1(p.inc) + '°'));
    sets.append(' and the equatorial speed to ');
    sets.appendChild(el('b', '', fmt1(p.veq) + ' km/s'));
    sets.append(' (v sin i = ' + fmt1(p.vsini) + ' km/s). Line width and depth, limb darkening and spots keep your settings.');
    card.appendChild(sets);

    const affects = p.flags.filter((f) => f.affects), other = p.flags.filter((f) => !f.affects);
    affects.forEach((f) => card.appendChild(el('p', 'warn', 'The catalogs disagree on a value that this preset uses. ' + f.text + '.')));

    const ul = el('ul');
    p.rows.forEach((r) => {
      const li = el('li');
      li.appendChild(el('span', 'q', r.name));
      li.appendChild(el('span', 'v', r.value));
      li.appendChild(el('span', 'basis ' + r.basis, r.basis === 'assumed' ? 'assumed' : r.basis));
      const src = el('span', 'src');
      src.append(r.url ? '' : r.source);
      if (r.url) src.appendChild(link(r.source, r.url));
      if (r.note) src.append(' · ' + r.note);
      li.appendChild(src);
      ul.appendChild(li);
    });
    card.appendChild(ul);

    if (other.length) {
      const d = el('details');
      d.appendChild(el('summary', '', 'Other differences between the catalogs (' + other.length + ')'));
      other.forEach((f) => d.appendChild(el('div', '', f.text + '.')));
      card.appendChild(d);
    }
    const foot = el('p', 'foot');
    foot.append('Retrieved ' + window.SIM_PRESETS.retrievedUtc.slice(0, 10) + ' from ');
    foot.appendChild(link('NASA Exoplanet Archive', p.links.nasa));
    foot.append(', ');
    foot.appendChild(link('Exoplanet.eu', p.links.eu));
    foot.append(' and ADS. Click "Real object" for the rules.');
    card.appendChild(foot);
    card.hidden = false;
  }

  function apply(p) {
    inc.value = String(p.inc);
    veq.value = String(p.veq);
    inc.dispatchEvent(new Event('input', { bubbles: true }));
    veq.dispatchEvent(new Event('input', { bubbles: true }));
    render(p);
  }

  select.addEventListener('change', () => {
    if (!select.value) { card.hidden = true; return; }
    const p = byId.get(select.value);
    if (!p) throw new Error('presets-ui: unknown preset ' + select.value);
    apply(p);
  });

  // moving either slider by hand ends the preset (programmatic changes are not trusted events)
  [inc, veq].forEach((s) => s.addEventListener('input', (e) => {
    if (e.isTrusted && select.value) { select.value = ''; card.classList.add('modified'); }
  }));
  form.addEventListener('reset', () => { card.hidden = true; card.textContent = ''; });
})();
